 s({t:'msg',text:'@평범AI 저장 테스트 메시지'});await sleep(800);
 s({t:'doc',text:'공유 문서 내용'});
 const meta0=[...A.ev].reverse().find(e=>e.t==='meta');const ai0=meta0.ais.find(a=>a.name==='평범AI');
