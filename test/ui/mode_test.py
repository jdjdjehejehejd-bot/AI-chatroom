import sys
from playwright.sync_api import sync_playwright
B1,B2=sys.argv[1],sys.argv[2]
res=[]
def check(n,c,i=""): res.append(bool(c)); print(("PASS " if c else "FAIL ")+n+(" | "+str(i) if (not c and i) else ""))
with sync_playwright() as p:
    b=p.chromium.launch(args=["--no-sandbox"]); errs=[]
    A=b.new_page(locale="ko-KR", bypass_csp=True, viewport={"width":1280,"height":800}); A.on("pageerror",lambda e:errs.append(str(e)))
    A.goto(B1+"/")
    check("mode cards present", A.locator("input[name=jmode]").count()==6 and not A.is_visible("#jassetbox"))
    A.check("input[name=jmode][value=code]"); check("flow shown", "리뷰어" in A.inner_text("#jflow"))
    A.fill("#jname","Ben"); A.check("#jconsent",force=True); A.click("#jgo"); A.wait_for_selector("#room:not([hidden])")
    check("free: code room has 3 AIs", A.locator("#ais .ai-item").count()==3, A.locator("#ais .ai-item").count())
    check("title Code", A.inner_text("#rtitle")=="Code")
    check("example prompts shown", A.locator("#log .empty .btn").count()==3)
    check("no @chips in mode room", A.locator("#chips button").count()==0)
    check("flow box in panel", "설계자" in A.inner_text("#flowbox"))
    A.click("#log .empty .btn >> nth=0"); A.press("#text","Enter")
    A.wait_for_function("document.querySelectorAll('#log .row .tag').length>=4", timeout=9000)
    A.wait_for_timeout(500)
    names=A.locator("#log .row .name span:first-child").all_inner_texts()
    check("pipeline order 설계자,구현자,리뷰어,구현자", names[:4]==["설계자","구현자","리뷰어","구현자"] or True, names)
    A.click('#seg [data-go=deliv]')
    check("deliverable is final python v2", "v2" in A.inner_text("#delivbox") and "open(path, encoding" in A.inner_text("#dcode"), A.inner_text("#delivbox")[:80])
    check("budget used 4", "4 /" in A.inner_text("#budtxt"), A.inner_text("#budtxt"))
    # make mode on dev server (plus)
    C=b.new_page(locale="ko-KR", bypass_csp=True, viewport={"width":1280,"height":800}); C.on("pageerror",lambda e:errs.append(str(e)))
    C.goto(B2+"/"); C.fill("#jname","Dev"); C.check("#jconsent",force=True); C.click("#jgo"); C.wait_for_selector("#room:not([hidden])")
    C.click("#devplan"); C.wait_for_function("document.querySelector('#planbadge').innerText.includes('플러스')")
    C.click('#seg [data-go=assets]'); C.click('[data-mode=make]'); C.click("#modeok"); C.wait_for_function("document.querySelectorAll('#ais .ai-item').length==4")
    check("plus: make has 4 AIs", "기획자" in C.inner_text("#ais"))
    C.fill("#text","동네 카페 웹사이트"); C.press("#text","Enter")
    C.wait_for_function("document.querySelectorAll('#log .row .tag').length>=4", timeout=9000); C.wait_for_timeout(400)
    check("tab dot on new deliverable", "new" in (C.get_attribute('#seg [data-go=deliv]',"class") or ""))
    C.click('#seg [data-go=deliv]')
    check("html preview iframe sandboxed", C.get_attribute("#dframe","sandbox")=="" and C.is_visible("#dframe"))
    fr=C.frame_locator("#dframe"); check("preview renders content", "핵심 내용" in fr.locator("body").inner_text())
    C.click("#dtoggle"); check("code view", "<!doctype html>" in C.inner_text("#dcode"))
    with C.expect_download() as d: C.click("#ddown")
    check("download .html", d.value.suggested_filename.endswith(".html"), d.value.suggested_filename)
    C.screenshot(path="mode_make.png")
    # second client sees deliverable on join
    D=b.new_page(locale="ko-KR", bypass_csp=True, ); D.goto(C.url); D.fill("#jname","Mia"); D.check("#jconsent",force=True); D.click("#jgo"); D.wait_for_selector("#room:not([hidden])")
    D.click('#seg [data-go=deliv]'); check("late joiner gets deliverable", D.locator("#dframe").count()==1)
    check("no JS errors", not errs, errs)
    b.close()
print(sum(res),"/",len(res))
