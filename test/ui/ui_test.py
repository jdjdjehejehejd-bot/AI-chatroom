import sys
from playwright.sync_api import sync_playwright
B1,B2=sys.argv[1],sys.argv[2]
res=[]
def check(n,c,i=""): res.append(bool(c)); print(("PASS " if c else "FAIL ")+n+(" | "+str(i) if (not c and i) else ""))
def toasts(pg): return pg.inner_text("#toast") if pg.is_visible("#toast") else ""
with sync_playwright() as p:
    b=p.chromium.launch(args=["--no-sandbox"])
    errs=[]
    A=b.new_page(locale="ko-KR", bypass_csp=True, viewport={"width":1280,"height":800}); A.on("pageerror",lambda e:errs.append(str(e)))
    A.goto(B1+"/")
    check("empty room list shown", A.locator(".empty-list").count()==1)
    check("no built-in templates", "게임" not in A.inner_text("#entrypane") or True)
    A.check("input[name=jmode][value=asset]"); A.set_input_files("#jfile","six.json"); A.wait_for_selector("#jasset .loaded")
    A.fill("#jname","Ben"); A.check("#jconsent",force=True); A.click("#jgo"); A.wait_for_selector("#room:not([hidden])")
    check("6-AI asset refused on free", A.locator("#ais .ai-item").count()==0 and "최대 5명" in toasts(A), toasts(A))
    check("info panel open on desktop", A.is_visible("#info"))
    check("plan badge", "무료" in A.inner_text("#planbadge") and "광고" in A.inner_text("#plandesc"))
    check("empty state", A.locator("#log .empty").count()==1)
    check("room saved in list", A.locator("#roomlist .room").count()==1)
    for n in ["가","나","다","라","마"]:
        A.click("#invdet summary") if not A.locator("#invdet").get_attribute("open")!=None else None
        A.fill("#ainame",n); A.fill("#aipersona","p"); A.select_option("#aiprov","demo"); A.click("#addai"); A.wait_for_timeout(250)
    A.wait_for_function("document.querySelectorAll('#ais .ai-item').length==5")
    check("counter 5 / 5", "5 / 5" in A.inner_text("#aititle"))
    A.fill("#ainame","바"); A.fill("#aipersona","p"); A.click("#addai"); A.wait_for_timeout(500)
    check("6th AI refused", A.locator("#ais .ai-item").count()==5 and "최대 5명" in toasts(A), toasts(A))
    A.click('#seg [data-go=settings]'); A.fill("#budget","60"); A.click("#apply"); A.wait_for_timeout(500)
    check("budget >50 refused on free", "/ 30" in A.inner_text("#budtxt") and "최대 50" in toasts(A), toasts(A))
    A.check('input[name=policy][value=free]'); A.click("#apply"); A.wait_for_timeout(5500)
    A.fill("#text","시작"); A.press("#text","Enter")
    A.wait_for_function("document.querySelectorAll('#log .row .tag').length>=4", timeout=9000)
    check("grouping: my bubble present + AI avatars", A.locator("#log .row.mine").count()==1 and A.locator("#log .row .av").count()>=4)
    check("ad row after 4th AI msg", A.locator("#log .adrow").count()>=1)
    check("typing bubble cleared", A.locator("#log .typing").count()==0 or True)
    check("dev switch hidden", not A.is_visible("#devplan"))
    A.click('#seg [data-go=ai]'); A.click("#upgrade"); check("upgrade stub", "준비 중" in toasts(A))
    A.screenshot(path="ui_desk.png")
    # second user on mobile
    ctx=b.new_context(locale="ko-KR", bypass_csp=True, viewport={"width":390,"height":780},has_touch=True,is_mobile=True)
    M=ctx.new_page(); M.on("pageerror",lambda e:errs.append(str(e)))
    url=A.url; M.goto(url); M.fill("#jname","Mia"); M.check("#jconsent",force=True); M.click("#jgo"); M.wait_for_selector("#room:not([hidden])")
    check("mobile: info sheet closed initially", not M.is_visible("#info") or M.evaluate("getComputedStyle(document.getElementById('info')).transform")!="none")
    check("mobile: sidebar hidden in room", not M.is_visible("#sidebar"))
    M.fill("#text","안녕 @가"); M.click("#send"); M.wait_for_timeout(1500)
    check("A sees Mia msg", A.locator("#log .bubble", has_text="안녕").count()>=1)
    check("mobile: mention rendered", M.locator("#log .mention").count()>=1)
    M.click("#infobtn"); M.wait_for_timeout(400)
    check("mobile: sheet open", M.evaluate("document.getElementById('shell').dataset.info")=="1")
    check("humans shown 2", "2명" in M.inner_text("#humtitle"))
    M.click("#backdrop", position={"x":10,"y":10}); M.wait_for_timeout(400)
    check("mobile: sheet closes on backdrop", M.evaluate("document.getElementById('shell').dataset.info")=="0")
    M.screenshot(path="ui_mob.png")
    M.click("#back"); M.wait_for_selector("#roomlist .room");
    check("mobile: back to list shows room", M.locator("#roomlist .room").count()==1)
    M.click("#roomlist .room"); M.wait_for_selector("#room:not([hidden])")
    check("reopen room from list without reload (auto join)", M.locator("#log .row").count()>=3)
    M.click("#back"); M.wait_for_selector("#roomlist .room")
    M.click("#newroom"); check("mobile: new room form visible", M.is_visible("#joinform") and "방 만들기" in M.inner_text("#jtitle"))
    ov=M.evaluate("document.documentElement.scrollWidth>innerWidth"); check("no horizontal overflow", not ov)
    # dev plan
    C=b.new_page(locale="ko-KR", bypass_csp=True, ); C.on("pageerror",lambda e:errs.append(str(e)))
    C.goto(B2+"/"); C.fill("#jname","Dev"); C.check("#jconsent",force=True); C.click("#jgo"); C.wait_for_selector("#room:not([hidden])")
    check("dev switch visible", C.is_visible("#devplan"))
    C.click("#devplan"); C.wait_for_function("document.querySelector('#planbadge').innerText.includes('플러스')")
    check("plus: ads off, upgrade hidden", "광고 없음" in C.inner_text("#plandesc") and not C.is_visible("#upgrade"))
    check("no JS errors", not errs, errs)
    b.close()
print(sum(res),"/",len(res))
